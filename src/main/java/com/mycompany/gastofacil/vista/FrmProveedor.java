    // Método para rellenar y refrescar la tabla con datos de MySQL
    public void actualizarTabla() {
        try {
            java.util.List<com.mycompany.gastofacil.modelo.Proveedor> lista = new com.mycompany.gastofacil.dao.ProveedorDAO().listar();
            javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel();
            modelo.addColumn("ID");
            modelo.addColumn("Nombre");
            modelo.addColumn("Teléfono");
            modelo.addColumn("Dirección");

            for (com.mycompany.gastofacil.modelo.Proveedor p : lista) {
                Object[] fila = new Object[4];
                fila[0] = p.getIdProveedor();
                fila[1] = p.getNombre();
                fila[2] = p.getTelefono();
                fila[3] = p.getDireccion();
                modelo.addRow(fila);
            }
            jTable1.setModel(modelo);
        } catch (Exception e) {
            System.out.println("Error al actualizar tabla gráfica: " + e.getMessage());
        }
    }

