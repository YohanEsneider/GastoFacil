    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {                                           
        String nombre = txtNombre.getText();
        String phone = txtTelefono.getText();
        String dir = txtDireccion.getText();

        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "El nombre es obligatorio");
            return;
        }

        com.mycompany.gastofacil.modelo.Proveedor p = new com.mycompany.gastofacil.modelo.Proveedor(nombre, phone, dir);
        new com.mycompany.gastofacil.dao.ProveedorDAO().insertar(p);

        javax.swing.JOptionPane.showMessageDialog(this, "¡Proveedor guardado!");
        actualizarTabla(); // Actualiza la tabla automáticamente
        
        txtNombre.setText("");
        txtTelefono.setText("");
        txtDireccion.setText("");
    }                                          

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {                                            
        if (txtIdProveedor.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un proveedor de la tabla");
            return; 
        }
        
        int id = Integer.parseInt(txtIdProveedor.getText());
        int confirmar = javax.swing.JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmar == javax.swing.JOptionPane.YES_OPTION) {
            new com.mycompany.gastofacil.dao.ProveedorDAO().eliminar(id);
            javax.swing.JOptionPane.showMessageDialog(this, "¡Proveedor eliminado!");
            actualizarTabla(); // Actualiza la tabla automáticamente
            
            txtIdProveedor.setText("");
            txtNombre.setText("");
            txtTelefono.setText("");
            txtDireccion.setText("");
        }
    }                                           

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {                                              
        if (txtIdProveedor.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un proveedor de la tabla");
            return;
        }
        int id = Integer.parseInt(txtIdProveedor.getText());
        String nombre = txtNombre.getText();
        String phone = txtTelefono.getText();
        String dir = txtDireccion.getText();

        com.mycompany.gastofacil.modelo.Proveedor p = new com.mycompany.gastofacil.modelo.Proveedor(id, nombre, phone, dir);
        new com.mycompany.gastofacil.dao.ProveedorDAO().actualizar(p);

        javax.swing.JOptionPane.showMessageDialog(this, "¡Proveedor actualizado!");
        actualizarTabla(); // Actualiza la tabla automáticamente

        txtIdProveedor.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtDireccion.setText("");
    }                                             

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {                                           
        txtIdProveedor.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtDireccion.setText("");
    }                                          


